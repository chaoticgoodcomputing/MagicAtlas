  public sealed record ScanRoot(string RelativePath, string Rationale, bool JsonOnly = false);

  public sealed record ArtifactRecord(
    string Path,
    string Kind,
    string Rule,
    string Basis,
    bool Acknowledged
  );

  public sealed record ExclusionRecord(string Path, string Rule);

  public sealed record ScanRootResult(string Path, string Rationale, bool Exists, int ArtifactCount);

  public sealed record CensusResult(
    IReadOnlyList<ScanRootResult> Roots,
    IReadOnlyList<ArtifactRecord> Artifacts,
    IReadOnlyList<ExclusionRecord> Exclusions,
    IReadOnlyList<string> UnconfirmedGeneratedDirectories
  )
  {
    /// <summary>The gate's failure set: artifacts no rule resolved and no human acknowledged.</summary>
    public IReadOnlyList<ArtifactRecord> Unclassified =>
      Artifacts.Where(a => a.Kind == NeedsHuman && !a.Acknowledged).ToList();
  }

  /// <summary>Locate the repository root by walking up for the workspace marker.</summary>
  public static string RepoRoot(string? start = null)
  {
    var dir = new DirectoryInfo(start ?? AppContext.BaseDirectory);
    while (dir is not null)
    {
      if (File.Exists(Path.Combine(dir.FullName, "MagicAtlas.slnx")))
        return dir.FullName;
      dir = dir.Parent;
    }
    throw new InvalidOperationException("Could not locate the repository root (MagicAtlas.slnx).");
  }

  /// <summary>Enumerate + classify every artifact on the declared surface. Pure w.r.t. the working
  /// tree: reads the filesystem, writes nothing.</summary>
  public static CensusResult Run(string repoRoot)
  {
    var source = SourceIndex.Build(repoRoot);
    var catalogOutputs = source.CatalogOutputSuffixes;

    var roots = new List<ScanRootResult>();
    var artifacts = new List<ArtifactRecord>();
    var exclusions = new List<ExclusionRecord>();

    foreach (var root in ScanRoots)
    {
      var abs = Path.Combine(repoRoot, root.RelativePath);
      if (!Directory.Exists(abs))
      {
        roots.Add(new ScanRootResult(root.RelativePath, root.Rationale, false, 0));
        continue;
      }

      var found = 0;
      foreach (var file in EnumerateFiles(abs))
      {
        var rel = Rel(repoRoot, file);
        if (root.JsonOnly && !rel.EndsWith(".json", StringComparison.OrdinalIgnoreCase))
          continue;

        var excluded = ExclusionRule(rel);
        if (excluded is not null)
        {
          exclusions.Add(new ExclusionRecord(rel, excluded));
          continue;
        }

        artifacts.Add(Classify(rel, catalogOutputs, source));
        found++;
      }
      roots.Add(new ScanRootResult(root.RelativePath, root.Rationale, true, found));
    }

    // Roots overlap (libs/ subsumes libs/atlas-flows/Data/_08_Reporting); dedupe on path.
    var deduped = artifacts
      .GroupBy(a => a.Path, StringComparer.Ordinal)
      .Select(g => g.First())
      .OrderBy(a => a.Path, StringComparer.Ordinal)
      .ToList();

    var dedupedExclusions = exclusions
      .GroupBy(e => e.Path, StringComparer.Ordinal)
      .Select(g => g.First())
      .OrderBy(e => e.Path, StringComparer.Ordinal)
      .ToList();

    // Second key for rule 5: a named generated directory must exist AND be confirmed by the source
    // index. A name whose regenerator was deleted or renamed is stale hand-maintained state.
    var unconfirmed = GeneratedDirectories
      .Keys.Where(d =>
        !Directory.Exists(Path.Combine(repoRoot, d))
        || source.DirectoryRegeneratorFor(d + "/probe") is null
      )
      .OrderBy(d => d, StringComparer.Ordinal)
      .ToList();

    return new CensusResult(roots, deduped, dedupedExclusions, unconfirmed);
  }

  private static ArtifactRecord Classify(
    string rel,
    IReadOnlyDictionary<string, string> catalogOutputs,
    SourceIndex source
  )
  {
    // 0. A human ruling always wins.
    if (HumanRulings.TryGetValue(rel, out var ruling))
      return new ArtifactRecord(rel, ruling.Kind, "HumanRuling", ruling.Basis, true);

    // 1. Declared Flowthru catalog output. Matched in BOTH directions, because a catalog path and an
    // artifact path can each be the longer one:
    //   - the artifact sits under a project's Data root, so its repo-relative path is the LONGER string
    //     and ends with the catalog's declared suffix (tests/magic-ast-tests/Data/_08_Reporting/x.json
    //     ends with _08_Reporting/x.json);
    //   - or the artifact has been PROMOTED out to a shorter repo-root path, so the catalog suffix is the
    //     longer string and ends with the artifact's whole path (the D1–D4 CardAtlas dumps are declared at
    //     _08_Reporting/dumps/card-ports.json and promoted to dumps/card-ports.json for atlas-api /
    //     atlas-diag to consume).
    // Both directions require a full path-segment match, so a promoted artifact is recognized while a
    // foreign file dropped into the same directory still falls through to the unclassified set.
    var norm = rel.Replace('\\', '/');
    var catalogHit = catalogOutputs.FirstOrDefault(kv =>
      norm.EndsWith(kv.Key, StringComparison.Ordinal)
      || kv.Key.EndsWith("/" + norm, StringComparison.Ordinal)
    );
    if (catalogHit.Key is not null)
      return new ArtifactRecord(
        rel,
        Derived,
        "FlowthruCatalogOutput",
        norm.EndsWith(catalogHit.Key, StringComparison.Ordinal)
          ? $"declared as a catalog item output at {catalogHit.Value}"
          : $"promoted copy of the catalog item output {catalogHit.Key}, declared at {catalogHit.Value}",
        false
      );

    // 2. Reporting layer — a flow output by the project's layering convention.
    if (("/" + rel.Replace('\\', '/')).Contains(ReportingSegment, StringComparison.Ordinal))
      return new ArtifactRecord(
        rel,
        Derived,
        "ReportingLayer",
        "lives under Data/_08_Reporting (Flowthru reporting layer: generated, gitignored)",
        false
      );

    // 3. Hand-authored gold directory.
    foreach (var (prefix, why) in EvidenceDirectories)
      if (rel.StartsWith(prefix, StringComparison.Ordinal))
        return new ArtifactRecord(rel, Evidence, "GoldConvention", why, false);

    // 4. A product source file writes this exact filename.
    var writer = source.WriterFor(Path.GetFileName(rel));
    if (writer is not null)
      return new ArtifactRecord(
        rel,
        Derived,
        "NamedWriter",
        $"regenerated by {writer}",
        false
      );

    // 5. Computed-filename member of a named, machine-confirmed generated directory.
    var dir = (Path.GetDirectoryName(rel) ?? "").Replace('\\', '/');
    if (
      !source.MentionsFileName(Path.GetFileName(rel))
      && GeneratedDirectories.ContainsKey(dir)
      && source.DirectoryRegeneratorFor(rel) is { } dirRegen
    )
      return new ArtifactRecord(
        rel,
        Derived,
        "GeneratedSibling",
        $"filename never appears in source; its directory is a named generated directory, confirmed "
          + $"regenerated by {dirRegen}",
        false
      );

    // 6. Unresolved.
    var ack = AcknowledgedAmbiguous.TryGetValue(rel, out var reason);
    return new ArtifactRecord(
      rel,
      NeedsHuman,
      "Unresolved",
      ack
        ? reason!
        : "No classification rule resolved this artifact and no human acknowledgment exists for it. "
          + "Add an entry to ArtifactClassifier.AcknowledgedAmbiguous (with the reason it is ambiguous) "
          + "or to ArtifactClassifier.HumanRulings (with the ruling), or give it a regeneration path.",
      ack
    );
  }

  /// <summary>Enumerate under <paramref name="root"/>, dropping excluded directories. Exclusion is
  /// tested on the path RELATIVE to the root — the repository may itself live under an excluded
  /// segment (an agent worktree under <c>.claude/worktrees/</c> is the live case), and testing the
  /// absolute path would silently census nothing.</summary>
  private static IEnumerable<string> EnumerateFiles(string root) =>
    Directory
      .EnumerateFiles(root, "*", SearchOption.AllDirectories)
      .Where(f => !IsExcludedPath(Path.GetRelativePath(root, f)));

  private static bool IsExcludedPath(string relativePath)
  {
    var p = "/" + relativePath.Replace('\\', '/');
    return ExcludedSegments.Any(s => p.Contains(s, StringComparison.Ordinal));
  }

  private static string Rel(string repoRoot, string abs) =>
    Path.GetRelativePath(repoRoot, abs).Replace('\\', '/');

  // ── Source-code index: the derivation evidence behind rules 1, 4 and 5 ───────────────────────────

  /// <summary>
  /// A one-pass index over PRODUCT source (tests/, libs/, tools/, apps/). Agent tooling under
  /// <c>.claude/</c> is deliberately NOT indexed: a skill script that rewrites a whitelist is agent
  /// convenience, not the product's derivation path, and treating it as one would silently promote
  /// hand-curated whitelists to "Derived".
  /// </summary>
  /// <remarks>
  /// <para><b>Write sites are resolved through symbols, never by proximity.</b> The first cut of this
  /// index called a file a writer when a write primitive sat within N lines of the filename literal,
  /// and it was wrong in exactly the way ADR 0004 warns about — it promoted
  /// <c>oracle-text-quarantine.json</c> to "Derived" off a sweep utility whose neighbouring
  /// <c>File.WriteAllText</c> targets a different file and whose very next line says the quarantine is
  /// "NOT auto-edited". A near-miss that silently reclassifies a hand-curated whitelist is worse than
  /// no rule at all: an unresolved artifact merely gets flagged.</para>
  /// <para>So each write call's arguments are followed through the file's local path-symbol
  /// definitions (up to <see cref="MaxSymbolDepth"/> hops — <c>path → SnapshotPath() →
  /// "captures-accepted-pairs.txt"</c> is a real two-hop chain here) and only the filename literals
  /// actually reachable count. A writer whose target is computed (<c>Slug(name) + ".json"</c>)
  /// resolves to no filename, which is correct — rule 5 picks those up by directory.</para>
  /// <para>Rule 5 reconstructs the <b>whole path</b> a regenerator writes into, not just the last
  /// segment. Matching on the segment alone made every file directly under <c>Fixtures/</c> look
  /// generated, because some regenerator somewhere mentions <c>"Fixtures"</c> — which silently
  /// swallowed the gate's own teeth probe.</para>
  /// </remarks>
  private sealed class SourceIndex
  {
    private static readonly string[] SourceRoots = ["tests", "libs", "tools", "apps"];
    private static readonly string[] SourceExtensions =
    [
      ".cs", ".py", ".sh", ".ts", ".tsx", ".js", ".mjs",
    ];

    /// <summary>How many symbol hops a write target is followed through.</summary>
    private const int MaxSymbolDepth = 4;

    /// <summary>How many lines of a call's argument list count as part of the write site.</summary>
    private const int CallSpanLines = 3;

    /// <summary>Cap on a symbol definition's body, for wrapped <c>Path.Combine(...)</c> calls.</summary>
    private const int MaxDefinitionLines = 8;

    private static readonly Regex FileLiteral = new(
      @"[A-Za-z0-9_\-][A-Za-z0-9._\-]*\.(?:json|jsonl|txt|csv|html|parquet)",
      RegexOptions.Compiled
    );

    /// <summary>Write primitives, each capturing its <b>target expression</b> (the first argument) so
    /// resolution follows what is actually being written to, not whatever identifiers happen to share
    /// the line. Shell redirects are deliberately absent: a shell <c>&gt;</c> cannot be attributed to a
    /// target without parsing the script (the corpus-edge-diff gate redirects into a <c>mktemp</c> two
    /// lines after merely reading its carve-out list), and a false attribution is worse than an
    /// unresolved artifact — the latter at least gets flagged.</summary>
    private static readonly Regex[] WriteTargets =
    [
      new(
        @"(?:File\.WriteAll(?:Text|Bytes|Lines)(?:Async)?|File\.Create|new StreamWriter|writeFileSync)\s*\(\s*([^,)\n]*)",
        RegexOptions.Compiled
      ),
      // Python: only a write/append mode counts — plain open() is a read.
      new(@"open\(\s*([^,)\n]*)\s*,\s*[""'][wa]", RegexOptions.Compiled),
      new(@"\.to_json\(\s*([^,)\n]*)", RegexOptions.Compiled),
    ];

    private static readonly Regex RegenerationMarker = new(
      @"UPDATE_SNAPSHOT|\bRegenerate\w*|--update\b|REGENERATE",
      RegexOptions.Compiled
    );

    private static readonly Regex AtPathLiteral = new(
      @"\.AtPath\(\s*\$?""([^""]+)""",
      RegexOptions.Compiled
    );

    /// <summary>A path-carrying symbol definition: <c>X =</c>, <c>X =></c>, or <c>X() =></c>.</summary>
    private static readonly Regex SymbolDefinition = new(
      @"\b([A-Za-z_]\w*)\s*(?:\(\s*\))?\s*(?:=>|=)(?![=>])",
      RegexOptions.Compiled
    );

    private static readonly Regex Identifier = new(@"\b([A-Za-z_]\w*)\b", RegexOptions.Compiled);

    /// <summary>A quoted token shaped like a single path segment.</summary>
    private static readonly Regex SegmentLiteral = new(
      @"[""']([A-Za-z0-9_][A-Za-z0-9._\-]*)[""']",
      RegexOptions.Compiled
    );

    /// <summary>Filenames mentioned anywhere in indexed source (rule 5's negative precondition).</summary>
    private readonly HashSet<string> _mentioned = new(StringComparer.Ordinal);

    /// <summary>filename -> the source site that writes it.</summary>
    private readonly Dictionary<string, string> _writers = new(StringComparer.Ordinal);

    /// <summary>reconstructed directory path -> the regenerating write site.</summary>
    private readonly Dictionary<string, string> _dirRegenerators = new(StringComparer.Ordinal);

    /// <summary>normalized catalog output suffix -> the catalog file:line that declares it.</summary>
    public Dictionary<string, string> CatalogOutputSuffixes { get; } = new(StringComparer.Ordinal);

    public static SourceIndex Build(string repoRoot)
    {
      var idx = new SourceIndex();
      foreach (var root in SourceRoots)
      {
        var abs = Path.Combine(repoRoot, root);
        if (!Directory.Exists(abs))
          continue;
        foreach (var file in EnumerateFiles(abs))
        {
          if (!SourceExtensions.Contains(Path.GetExtension(file).ToLowerInvariant()))
            continue;
          idx.Ingest(repoRoot, file);
        }
      }
      return idx;
    }

    private void Ingest(string repoRoot, string absFile)
    {
      var rel = Rel(repoRoot, absFile);
      string[] lines;
      try
      {
        lines = File.ReadAllLines(absFile);
      }
      catch (IOException)
      {
        return;
      }

      var hasRegenMarker = false;
      foreach (var line in lines)
      {
        if (RegenerationMarker.IsMatch(line))
          hasRegenMarker = true;
        foreach (Match m in FileLiteral.Matches(line))
          _mentioned.Add(m.Value);
      }

      for (var i = 0; i < lines.Length; i++)
        foreach (Match m in AtPathLiteral.Matches(lines[i]))
        {
          var suffix = NormalizeCatalogPath(m.Groups[1].Value);
          if (suffix.Length > 0)
            CatalogOutputSuffixes.TryAdd(suffix, $"{rel}:{i + 1}");
        }

      var symbols = BuildSymbolTable(lines);

      for (var i = 0; i < lines.Length; i++)
      {
        var target = WriteTargetExpression(lines, i);
        if (target is null)
          continue;

        var reached = Reachable(target, symbols);

        foreach (var file in FileLiteral.Matches(target).Select(m => m.Value)
          .Concat(reached.SelectMany(s => symbols[s].Files)))
          _writers.TryAdd(file, $"{rel}:{i + 1}");

        // Rule 5's evidence: the directory this write site targets, reconstructed from the ordered
        // path-segment literals of every symbol the target expression reaches. Only regenerators
        // qualify — a plain report writer is not evidence that its directory is wholly generated.
        if (!hasRegenMarker)
          continue;
        foreach (var dir in reached.Select(s => symbols[s].DirectoryPath).Where(d => d.Length > 0))
          _dirRegenerators.TryAdd(dir, $"{rel}:{i + 1}");
      }
    }

    /// <summary>The target expression of a write call starting on <paramref name="i"/>, or null if the
    /// line is not a write. An argument list wrapped onto the next line ("File.WriteAllText(\n
    /// WhitelistPath(),") is followed for <see cref="CallSpanLines"/> lines.</summary>
    private static string? WriteTargetExpression(string[] lines, int i)
    {
      foreach (var rx in WriteTargets)
      {
        var m = rx.Match(lines[i]);
        if (!m.Success)
          continue;
        var expr = m.Groups[1].Value.Trim();
        for (var j = i + 1; expr.Length == 0 && j < lines.Length && j - i < CallSpanLines; j++)
          expr = lines[j].Split(',')[0].Trim();
        return expr;
      }
      return null;
    }

    private sealed record SymbolInfo(
      HashSet<string> Files,
      HashSet<string> Refs,
      string DirectoryPath
    );

    /// <summary>The file's local path-symbol table: for each definition, the filename literals it
    /// contains, the identifiers it refers to, and the directory path its ordered segment literals
    /// spell out.</summary>
    private static Dictionary<string, SymbolInfo> BuildSymbolTable(string[] lines)
    {
      var table = new Dictionary<string, SymbolInfo>(StringComparer.Ordinal);
      for (var i = 0; i < lines.Length; i++)
      {
        var def = SymbolDefinition.Match(lines[i]);
        if (!def.Success)
          continue;
        var name = def.Groups[1].Value;
        var body = lines[i][(def.Index + def.Length)..];
        for (var j = i + 1; j < lines.Length && j - i < MaxDefinitionLines && !body.Contains(';'); j++)
          body += "\n" + lines[j];

        var files = FileLiteral.Matches(body).Select(m => m.Value).ToHashSet(StringComparer.Ordinal);
        var refs = Identifier
          .Matches(body)
          .Select(m => m.Value)
          .Where(id => id != name)
          .ToHashSet(StringComparer.Ordinal);
        var segments = SegmentLiteral
          .Matches(body)
          .Select(m => m.Groups[1].Value)
          .Where(s => !files.Contains(s) && !s.Contains('.'))
          .ToList();

        // A name can be defined more than once in a file (a `var path = …` in one method, another in
        // the next). C#-accurate scoping is out of proportion here; UNION the definitions instead —
        // per-file over-approximation, which at worst widens rule 4 and can never silently narrow it.
        var dirPath = segments.Count >= 2 ? string.Join('/', segments) : "";
        if (table.TryGetValue(name, out var prior))
        {
          files.UnionWith(prior.Files);
          refs.UnionWith(prior.Refs);
          if (dirPath.Length == 0)
            dirPath = prior.DirectoryPath;
        }
        table[name] = new SymbolInfo(files, refs, dirPath);
      }
      return table;
    }

    /// <summary>Every symbol reachable from a call's argument text, following aliases.</summary>
    private static HashSet<string> Reachable(
      string callText,
      Dictionary<string, SymbolInfo> symbols
    )
    {
      var reached = new HashSet<string>(StringComparer.Ordinal);
      var frontier = Identifier.Matches(callText).Select(m => m.Value).ToList();
      for (var depth = 0; depth < MaxSymbolDepth && frontier.Count > 0; depth++)
      {
        var next = new List<string>();
        foreach (var id in frontier)
        {
          if (!symbols.TryGetValue(id, out var info) || !reached.Add(id))
            continue;
          next.AddRange(info.Refs);
        }
        frontier = next;
      }
      return reached;
    }

    /// <summary>Strip the catalog's <c>{_basePath}</c> interpolation and collapse <c>..</c> so the
    /// declared output becomes a path suffix matchable against a repo-relative artifact path.</summary>
    private static string NormalizeCatalogPath(string raw)
    {
      var s = raw.Replace('\\', '/');
      var brace = s.LastIndexOf('}');
      if (brace >= 0)
        s = s[(brace + 1)..];
      s = s.TrimStart('/');
      var parts = new List<string>();
      foreach (var seg in s.Split('/', StringSplitOptions.RemoveEmptyEntries))
      {
        if (seg == "..")
        {
          if (parts.Count > 0)
            parts.RemoveAt(parts.Count - 1);
          continue;
        }
        if (seg == ".")
          continue;
        parts.Add(seg);
      }
      var normalized = string.Join('/', parts);
      // Require at least dir/file so a bare filename cannot match half the repo.
      return normalized.Contains('/') ? "/" + normalized : "";
    }

    public bool MentionsFileName(string fileName) => _mentioned.Contains(fileName);

    /// <summary>The source site that writes <paramref name="fileName"/>, or null.</summary>
    public string? WriterFor(string fileName) =>
      _writers.TryGetValue(fileName, out var site) ? site : null;

    /// <summary>The regenerator that writes into the artifact's containing directory — matched on the
    /// FULL reconstructed path, so a regenerator that merely mentions <c>"Fixtures"</c> does not claim
    /// everything under it.</summary>
    public string? DirectoryRegeneratorFor(string relPath)
    {
      var dir = (Path.GetDirectoryName(relPath.Replace('\\', '/')) ?? "").Replace('\\', '/');
      if (dir.Length == 0)
        return null;
      foreach (var (candidate, site) in _dirRegenerators)
        if (dir.Equals(candidate, StringComparison.Ordinal)
          || dir.EndsWith("/" + candidate, StringComparison.Ordinal))
          return site;
      return null;
    }
  }
