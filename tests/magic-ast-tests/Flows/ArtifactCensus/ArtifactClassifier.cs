using System.Text.RegularExpressions;

namespace MagicAtlas.Ast.Tests.Flows.ArtifactCensus;

/// <summary>
/// The ADR-0004 §1 artifact classifier — the single, pure, filesystem-driven implementation shared by
/// the <c>ArtifactCensus</c> Flowthru flow (which writes the human-readable manifest) and the NUnit
/// classification gate (which asserts the invariant). Deliberately NOT a Flowthru step: a step would
/// bind the gate to a generated artifact, and the gate must hold on a clean checkout with no
/// <c>_08_Reporting</c> present.
/// </summary>
/// <remarks>
/// <para><b>The classification is derived, not stored.</b> ADR 0004's whole point is that a
/// hand-maintained claim <i>about</i> the data is the enemy, so every kind here is computed from a
/// structural fact about the repository:</para>
/// <list type="number">
///   <item><b>Catalog output</b> — the path is the <c>.AtPath(...)</c> target of a Flowthru catalog
///     item, i.e. a flow declares it as an output. <b>Derived</b>, definitively.</item>
///   <item><b>Reporting layer</b> — the path lives under a <c>Data/_08_Reporting/</c> directory.
///     <b>Derived</b> by the project's own layering convention.</item>
///   <item><b>Gold convention</b> — the path lives under a hand-authored fixture directory
///     (<c>HandParsedCards</c>, <c>Interactions/golds</c>, …). <b>Evidence</b>.</item>
///   <item><b>Named writer</b> — a product source file writes this exact filename: the target
///     expression of a write call resolves to the literal through the file's local path symbols.
///     <b>Derived</b> — this is how frozen computations (snapshots, expectation pins) are caught.</item>
///   <item><b>Generated sibling</b> — the filename never appears literally in any source file, but the
///     full directory path it lives in is reconstructed from a regenerator's write target. Catches
///     computed-filename snapshot families (<c>Slug(name) + ".json"</c>). <b>Derived</b>.</item>
/// </list>
/// <para>Anything that survives all five is <b>needs-human-classification</b>. That is a success
/// state, not a failure — but it must be <i>acknowledged</i>: see
/// <see cref="AcknowledgedAmbiguous"/>, the one hand-maintained table in this file, and
/// <see cref="HumanRulings"/>, which is where an acknowledgment goes to die once a human rules on it.
/// The gate is stateless: <i>every discovered artifact is either resolved by a rule above or carries
/// an explicit acknowledgment</i>. It is not a count and it does not ratchet.</para>
/// </remarks>
public static class ArtifactClassifier
