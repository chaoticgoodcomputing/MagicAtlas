  /// <summary>Explicitly named, reported (never silent) exclusions. Each carries the rule that
  /// excluded it so the manifest shows what was set aside and why.</summary>
  public static string? ExclusionRule(string repoRelPath)
  {
    var name = Path.GetFileName(repoRelPath);
    var ext = Path.GetExtension(repoRelPath).ToLowerInvariant();

    if (ext is ".cs" or ".py" or ".ts" or ".tsx" or ".js" or ".sh" or ".csproj" or ".props" or ".targets" or ".lscache" or ".toml" or ".lock")
      return "Source";
    if (ext is ".md")
      return "Documentation";
    if (name is "project.json" or "appsettings.json" or "appsettings.Local.json" or "package.json" or "tsconfig.json" or "nx.json")
      return "BuildConfiguration";
    if (name is ".gitkeep" or ".gitignore" or ".DS_Store")
      return "VcsPlumbing";
    return null;
  }

